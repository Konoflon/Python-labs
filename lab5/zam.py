def fibonacci_closure():
    """Внешняя функция, которая создаёт замыкание для генерации чисел Фибоначчи"""
    a = 0  # первое число Фибоначчи (F0)
    b = 1  # второе число Фибоначчи (F1)
    
    def get_next():
        """Внутренняя функция — замыкание, которое помнит a и b"""
        nonlocal a, b  # говорим Python: a и b — не локальные, они из внешней функции
        result = a     # сохраняем текущее число
        a, b = b, a + b  # обновляем пару для следующего вызова
        return result   # возвращаем текущее число Фибоначчи
    
    return get_next  # возвращаем функцию, а не её результат

# Создаём замыкание
fib = fibonacci_closure()

